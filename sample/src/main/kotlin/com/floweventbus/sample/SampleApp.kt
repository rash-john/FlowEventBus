package com.floweventbus.sample

import android.app.Application
import com.floweventbus.FlowEventBus
import com.floweventbus.android.android

class SampleApp : Application() {
    override fun onCreate() {
        super.onCreate()
        FlowEventBus.builder()
            .android(tag = "FlowEventBusSample")   // Logcat logger
            .addIndex(SampleEventBusIndex)         // generated by floweventbus-ksp, skips reflection
            .apply { throwSubscriberException = false } // keep false so the "Throw" demo shows SubscriberExceptionEvent
            .installDefaultFlowEventBus()
    }
}

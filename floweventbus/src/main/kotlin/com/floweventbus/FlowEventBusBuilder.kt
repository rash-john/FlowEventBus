package com.floweventbus

import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.ExperimentalCoroutinesApi

class FlowEventBusBuilder internal constructor() {
    var logSubscriberExceptions: Boolean = true
    var logNoSubscriberMessages: Boolean = true
    var sendSubscriberExceptionEvent: Boolean = true
    var sendNoSubscriberEvent: Boolean = true

    /** Rethrow subscriber exceptions to the poster (POSTING/direct delivery). Handy in debug builds/tests. */
    var throwSubscriberException: Boolean = false

    /** Deliver events to subscribers of super classes / interfaces too. Disable for a little speed. */
    var eventInheritance: Boolean = true

    var logger: FlowEventBusLogger = FlowEventBusLogger.Console

    /** Null = auto-detect `Dispatchers.Main`. */
    var mainThreadSupport: MainThreadSupport? = null

    /** Must be sequential; BACKGROUND events are delivered one after another. */
    @OptIn(ExperimentalCoroutinesApi::class)
    var backgroundDispatcher: CoroutineDispatcher = Dispatchers.IO.limitedParallelism(1)

    var asyncDispatcher: CoroutineDispatcher = Dispatchers.IO

    internal val indexes = ArrayList<SubscriberIndex>()

    /** Adds an index generated by `floweventbus-ksp`; one per module that has subscribers. */
    fun addIndex(index: SubscriberIndex) = apply { indexes += index }

    fun build(): FlowEventBus = FlowEventBus(this)

    /** Builds a bus and makes it [FlowEventBus.getDefault]. Must be called before the default bus is first used. */
    fun installDefaultFlowEventBus(): FlowEventBus = build().also { FlowEventBus.installDefault(it) }
}
